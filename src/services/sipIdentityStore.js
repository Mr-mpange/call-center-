const crypto = require('crypto');
const fs = require('fs');
const path = require('path');
const dashboardStore = require('../utils/dashboardStore');
const asteriskCli = require('./asteriskCli');

function secretKey() {
  const secret = process.env.SIP_CREDENTIAL_SECRET || process.env.AUTH_SECRET;
  if (!secret || secret.length < 16) {
    throw new Error('SIP_CREDENTIAL_SECRET (or AUTH_SECRET) must be configured before provisioning SIP identities');
  }
  return crypto.createHash('sha256').update(`mpange-sip:${secret}`).digest();
}

function encryptPassword(password) {
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', secretKey(), iv);
  const encrypted = Buffer.concat([cipher.update(String(password), 'utf8'), cipher.final()]);
  const tag = cipher.getAuthTag();
  return `v1:${iv.toString('base64url')}:${tag.toString('base64url')}:${encrypted.toString('base64url')}`;
}

function decryptPassword(payload) {
  const parts = String(payload || '').split(':');
  if (parts.length !== 4 || parts[0] !== 'v1') throw new Error('Invalid SIP credential payload');
  const iv = Buffer.from(parts[1], 'base64url');
  const tag = Buffer.from(parts[2], 'base64url');
  const encrypted = Buffer.from(parts[3], 'base64url');
  const decipher = crypto.createDecipheriv('aes-256-gcm', secretKey(), iv);
  decipher.setAuthTag(tag);
  return Buffer.concat([decipher.update(encrypted), decipher.final()]).toString('utf8');
}

function usernameFor(tenantId, userId) {
  const digest = crypto.createHash('sha256').update(`${tenantId}:${userId}`).digest('hex').slice(0, 24);
  return `mpange_${digest}`;
}

function ttlSeconds() {
  const value = Number(process.env.SIP_AGENT_CREDENTIAL_TTL_SECONDS || 8 * 60 * 60);
  return Number.isFinite(value) && value >= 300 ? Math.floor(value) : 8 * 60 * 60;
}

function provisioningDisabled() {
  return String(process.env.ASTERISK_PJSIP_PROVISIONING || 'file').toLowerCase() === 'disabled';
}

function agentsFile() {
  return path.resolve(process.env.ASTERISK_PJSIP_AGENTS_FILE
    || path.join(process.cwd(), 'infrastructure', 'asterisk', 'runtime', 'pjsip-agents.conf'));
}

function pjsipBlock(identity, password) {
  const username = identity.username;
  return [
    `; Managed by MPANGE for tenant ${identity.tenantId} agent ${identity.agentId}`,
    `[${username}-auth]`,
    'type=auth',
    'auth_type=userpass',
    `username=${username}`,
    `password=${password}`,
    '',
    `[${username}]`,
    'type=aor',
    'max_contacts=3',
    'remove_existing=yes',
    'maximum_expiration=3600',
    '',
    `[${username}]`,
    'type=endpoint',
    'transport=transport-wss',
    'context=from-webrtc',
    'disallow=all',
    // Prefer the transcodable narrowband codecs: this gateway image ships
    // without codec_opus, so an opus- negotiated browser leg could not be
    // bridged to a PCMU trunk caller ("Unable to find a codec translation
    // path: (opus) -> (ulaw)"). Opus stays available as the last choice for
    // remotes that can only speak it (both legs then negotiate opus and no
    // transcoding is needed).
    'allow=ulaw,alaw,opus',
    `auth=${username}-auth`,
    `aors=${username}`,
    'webrtc=yes',
    'dtls_auto_generate_cert=yes',
    'media_encryption=dtls',
    'ice_support=yes',
    'rtcp_mux=yes',
    'use_avpf=yes',
    'media_use_received_transport=yes',
    'direct_media=no',
    'rtp_symmetric=yes',
    'force_rport=yes',
    'rewrite_contact=yes',
    '',
  ].join('\n');
}

let lastProvisionedContent = null;
let provisioningQueue = Promise.resolve();

function renderAgentsFile(identities) {
  const lines = [
    '; AUTO-GENERATED by src/services/sipIdentityStore.js.',
    '; Contains per-agent browser WebRTC endpoints. Never expose this file or its passwords.',
    '',
  ];
  for (const identity of identities) {
    let password;
    try { password = decryptPassword(identity.passwordEnc); } catch { continue; }
    lines.push(pjsipBlock(identity, password));
  }
  return lines.join('\n');
}

async function provisionAll() {
  if (provisioningDisabled()) return { provisioned: false, reason: 'SIP provisioning is disabled' };
  provisioningQueue = provisioningQueue.then(async () => {
    const identities = dashboardStore.listSipAgentIdentities({ status: 'active' })
      .filter((identity) => !identity.expiresAt || Date.parse(identity.expiresAt) > Date.now());
    const content = renderAgentsFile(identities);
    if (content === lastProvisionedContent) return { provisioned: false, unchanged: true, count: identities.length };
    const file = agentsFile();
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const temporary = `${file}.${process.pid}.tmp`;
    fs.writeFileSync(temporary, content, { mode: 0o600 });
    fs.renameSync(temporary, file);
    lastProvisionedContent = content;
    const ownership = await asteriskCli.chownRuntimeFile();
    const reload = await asteriskCli.reloadPjsip();
    return { provisioned: true, count: identities.length, file, ownership, reload };
  }).catch((error) => ({ provisioned: false, reason: error.message }));
  return provisioningQueue;
}

function businessIdsForUser(user, tenantId, businesses) {
  const voiceAgentRouting = require('./voiceAgentRouting');
  return voiceAgentRouting.membershipsForUser(user, tenantId, businesses).map(String);
}

async function ensureIdentity({ tenantId, user, businesses, rotate = false }) {
  const memberships = businessIdsForUser(user, tenantId, businesses);
  if (!memberships.length) {
    const error = new Error('No browser-agent business membership is configured for this user');
    error.status = 403;
    throw error;
  }
  const configuredAgent = businesses
    .flatMap((business) => (business.agents || []).map((agent) => ({ business, agent })))
    .find(({ business, agent }) => agent.type === 'web'
      && memberships.includes(String(business.id))
      && (String(agent.userId || '') === String(user.id)
        || String(agent.email || '').toLowerCase() === String(user.email || '').toLowerCase()
        || String(agent.clientName || '') === require('./voiceAgentRouting').clientNameFor(tenantId, user.email)));
  const agentId = configuredAgent?.agent?.id || user.id;
  const username = usernameFor(tenantId, user.id);
  const existing = dashboardStore.getSipAgentIdentityByUser(tenantId, user.id);
  const expired = existing?.expiresAt ? Date.parse(existing.expiresAt) <= Date.now() : false;
  const needsPassword = !existing || existing.status !== 'active' || expired || rotate;
  const password = needsPassword ? crypto.randomBytes(32).toString('hex') : decryptPassword(existing.passwordEnc);
  const expiresAt = new Date(Date.now() + ttlSeconds() * 1000).toISOString();
  const identity = dashboardStore.upsertSipAgentIdentity({
    tenantId,
    userId: user.id,
    agentId,
    email: user.email,
    username,
    passwordEnc: needsPassword ? encryptPassword(password) : existing.passwordEnc,
    businessIds: memberships,
    status: 'active',
    expiresAt: needsPassword || !existing?.expiresAt ? expiresAt : existing.expiresAt,
  });
  await provisionAll();
  return { identity, password, rotated: needsPassword };
}

function browserCredentials({ identity, password }) {
  const sipDomain = process.env.ASTERISK_SIP_DOMAIN || 'localhost';
  return {
    username: identity.username,
    password,
    aor: `sip:${identity.username}@${sipDomain}`,
    wsUrl: process.env.ASTERISK_WSS_URL || 'wss://localhost:8089/ws',
    sipDomain,
    expiresAt: identity.expiresAt,
    businessIds: identity.businessIds,
  };
}

function identityForUser(tenantId, userId) {
  const identity = dashboardStore.getSipAgentIdentityByUser(tenantId, userId);
  if (!identity || identity.status !== 'active') return null;
  if (identity.expiresAt && Date.parse(identity.expiresAt) <= Date.now()) return null;
  return identity;
}

function passwordForIdentity(identity) {
  return decryptPassword(identity.passwordEnc);
}

function identityForAgent(tenantId, agent = {}) {
  const byUser = agent.userId ? dashboardStore.getSipAgentIdentityByUser(tenantId, agent.userId) : null;
  if (byUser && byUser.status === 'active') return byUser;
  if (agent.email) {
    const identities = dashboardStore.listSipAgentIdentities({ tenantId, status: 'active' });
    return identities.find((identity) => String(identity.email).toLowerCase() === String(agent.email).toLowerCase())
      || identities.find((identity) => String(identity.agentId) === String(agent.id))
      || null;
  }
  return null;
}

async function revokeIdentity(tenantId, userId) {
  const revoked = dashboardStore.revokeSipAgentIdentity(tenantId, userId);
  await provisionAll();
  return revoked;
}

async function rotateIdentity(tenantId, userId) {
  const existing = dashboardStore.getSipAgentIdentityByUser(tenantId, userId);
  if (!existing) return null;
  const password = crypto.randomBytes(32).toString('hex');
  const expiresAt = new Date(Date.now() + ttlSeconds() * 1000).toISOString();
  const identity = dashboardStore.upsertSipAgentIdentity({
    ...existing,
    passwordEnc: encryptPassword(password),
    status: 'active',
    expiresAt,
  });
  await provisionAll();
  return { identity, password };
}

async function sweepExpired() {
  const count = dashboardStore.revokeExpiredSipAgentIdentities();
  if (count > 0) await provisionAll();
  return count;
}

module.exports = {
  encryptPassword, decryptPassword, usernameFor,
  ensureIdentity, identityForUser, identityForAgent, passwordForIdentity, browserCredentials,
  revokeIdentity, rotateIdentity, provisionAll, sweepExpired, agentsFile,
  __test: { pjsipBlock, renderAgentsFile },
};
